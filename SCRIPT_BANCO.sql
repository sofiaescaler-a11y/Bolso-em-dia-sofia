CREATE TRIGGER TG_AI_DIA_TRABALHADO
FOR DIA_TRABALHADO ACTIVE AFTER INSERT OR UPDATE OR DELETE 
AS 
BEGIN
	
	IF (INSERTING) THEN 
	BEGIN
		INSERT INTO MOVIMENTACAO (VALOR, DATA_MOVIMENTACAO, DESCRICAO, TIPO, ID_USUARIO, ID_CATEGORIA, STATUS, ID_DIA_TRABALHADO)
		VALUES (:NEW.VALOR_TOTAL, :NEW.DATA_TRABALHO, 'Receita cadastrada pelo Dia Trabalhado', 2, :NEW.ID_USUARIO, 2, 1, :NEW.ID_DIA_TRABALHADO);
	END

	ELSE iF (UPDATING) THEN
	BEGIN
		IF (:NEW.PACOTES_COLETADOS <> :OLD.PACOTES_COLETADOS) THEN 
		BEGIN 
			UPDATE MOVIMENTACAO SET VALOR = :NEW.VALOR_TOTAL
			WHERE ID_DIA_TRABALHADO = :NEW.ID_DIA_TRABALHADO;
		END

		IF (:NEW.STATUS = 0 AND OLD.STATUS = 1) THEN 
		BEGIN
			UPDATE MOVIMENTACAO SET STATUS = 0
			WHERE ID_DIA_TRABALHADO = :NEW.ID_DIA_TRABALHADO;
		END
		ELSE IF (:NEW.STATUS = 1 AND OLD.STATUS = 0) THEN
			UPDATE MOVIMENTACAO SET STATUS = 1
			WHERE ID_DIA_TRABALHADO = :NEW.ID_DIA_TRABALHADO;
	END	

	ELSE IF (DELETING) THEN
	BEGIN
		DELETE FROM MOVIMENTACAO
		WHERE ID_DIA_TRABALHADO = :OLD.ID_DIA_TRABALHADO;
	END
END




